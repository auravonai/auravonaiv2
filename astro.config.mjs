// @ts-check
import { defineConfig, fontProviders } from 'astro/config';
import node from '@astrojs/node';

import { writeFile } from 'node:fs/promises';

import tailwindcss from '@tailwindcss/vite';

import { marketingRedirects } from './src/lib/marketing.ts';

/**
 * Writes a host-level `_redirects` file into the build output.
 *
 * Astro's own `redirects` option emits meta-refresh HTML in `output: 'static'`
 * — a real redirect, but a weaker signal than a 301 and unable to carry a
 * status code. This integration additionally emits the Netlify / Cloudflare
 * Pages `_redirects` format so the host answers with a true 301.
 *
 * It writes to `dist/` rather than `public/` on purpose: `public/` is copied
 * into the build early, so a generated file there is a source file that lies
 * about being source. This is a build artefact and belongs with the artefacts.
 *
 * On Vercel, translate these lines to `vercel.json` `redirects` with
 * `"permanent": true`. On nginx, `return 301`. `src/lib/marketing.ts` stays
 * the source of truth either way.
 */
function hostRedirects() {
  return {
    name: 'auravon:host-redirects',
    hooks: {
      // `writeFile` is imported at the top of this file rather than
      // dynamically here: by the time this hook runs, Vite's module runner is
      // closed and a dynamic import throws.
      'astro:build:done': async ({ dir, logger }) => {
        const entries = Object.entries(marketingRedirects());
        const width = Math.max(...entries.map(([from]) => from.length));

        const body = [
          '# Generated at build time by the auravon:host-redirects integration.',
          '# Source of truth: src/lib/marketing.ts — do not edit by hand.',
          '',
          ...entries.map(([from, to]) => `${from.padEnd(width)}  ${to}  301`),
          '',
        ].join('\n');

        await writeFile(new URL('_redirects', dir), body, 'utf8');
        logger.info(`wrote ${entries.length} 301 rules to _redirects`);
      },
    },
  };
}

// https://astro.build/config
export default defineConfig({
  integrations: [hostRedirects()],

  site: 'https://auravonai.com',

  // The 34 digital-marketing pages moved from /services/* to
  // /digital-marketing/* when the two business lines were split into separate
  // namespaces. Every old URL redirects to its new home.
  //
  // In `output: 'static'` Astro writes these as HTML files carrying a
  // `<meta http-equiv="refresh">`, which is a real but weaker signal than a
  // 301 and cannot carry a status code. `public/_redirects` (generated by
  // `npm run redirects`) gives the true 301 on any host that reads that
  // format — Netlify and Cloudflare Pages do. On Vercel, port it to
  // `vercel.json`. Keep both: the config form works everywhere including
  // `astro preview`, the host form is the one Google prefers.
  redirects: marketingRedirects(),

  // Every marketing page is prerendered — `output: 'static'` is still the
  // default for the whole site. The adapter exists only so the two Razorpay
  // endpoints under src/pages/api/ (which opt out via `prerender = false`)
  // can run on demand; the reference implementation had them as Next.js
  // route handlers and the payment page calls both.
  //
  // Swap this adapter for @astrojs/vercel, @astrojs/netlify, or
  // @astrojs/cloudflare to match wherever this ends up deployed.
  output: 'static',
  adapter: node({ mode: 'standalone' }),

  // DESIGN.md specifies Geist for every display/body/button/label surface and
  // Geist Mono for the technical layer (eyebrows, code, terminal mockups).
  // Both are self-hosted and preloaded by Astro's Fonts API — no external
  // requests, no layout shift.
  fonts: [
    {
      provider: fontProviders.google(),
      name: 'Geist',
      cssVariable: '--font-geist',
      // DESIGN.md caps the display weight at 600. 400/500/600 is the whole
      // working set — do not add 700.
      weights: ['400 600'],
      styles: ['normal'],
      subsets: ['latin'],
      fallbacks: ['Inter', 'system-ui', 'sans-serif'],
    },
    {
      provider: fontProviders.google(),
      name: 'Geist Mono',
      cssVariable: '--font-geist-mono',
      weights: [400],
      styles: ['normal'],
      subsets: ['latin'],
      fallbacks: ['ui-monospace', 'SFMono-Regular', 'Menlo', 'monospace'],
    },
  ],

  // On MPA script inlining — tested, then deliberately left at Astro's default.
  //
  // Astro inlines small scripts into the HTML to save a request. On an MPA
  // that looks like the wrong trade: the same ~6.6 KB of theme, reveal, and
  // navbar JS is re-sent inside all 91 documents, and inline code cannot be
  // cached across navigations the way an external file can.
  //
  // `vite.environments.client.build.assetsInlineLimit: 0` plus
  // `build.inlineStylesheets: 'never'` was measured and did NOT fix it —
  // Astro's script inlining is its own heuristic, not Vite's asset limit, so
  // inline JS stayed at 19,455 B on the homepage. What it did do was split the
  // CSS into three files (two stylesheet requests on the homepage instead of
  // one) and add ~75 KB of total HTML. Net worse, so it was reverted.
  //
  // If this becomes worth chasing, the lever is moving the shared behaviour
  // into a single `src/scripts/*.ts` entry imported via `<script src>` — not a
  // config flag.

  vite: {
    plugins: [tailwindcss()],
  },
});
